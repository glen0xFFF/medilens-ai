/** mulberry32, as in probes.parity.ts. */
function prng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const pick = <T>(rnd: () => number, xs: readonly T[]): T => {
  const x = xs[Math.floor(rnd() * xs.length)];
  if (x === undefined) throw new Error('pick from an empty list');
  return x;
};

const byCodeUnits = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

/** No lone surrogate anywhere in an encoded line. */
const wellFormed = (s: string) => !/\p{Cs}/u.test(s);

/* ------------------------------------------------ 1. case-fold tables */

type Range = [number, number];

function ranges(test: (cp: number) => boolean): Range[] {
  const rs: Range[] = [];
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    if (!test(cp)) continue;
    const last = rs.at(-1);
    if (last !== undefined && last[1] === cp - 1) last[1] = cp;
    else rs.push([cp, cp]);
  }
  return rs;
}

function caseFoldTables(): object {
  const lnFold = /^[\p{L}\p{N}]$/iu;
  const cased = new Set<number>();
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const s = String.fromCodePoint(cp);
    for (const m of [s.toLowerCase(), s.toUpperCase()]) {
      if (m === s) continue;
      cased.add(cp);
      const cps = [...m];
      if (cps.length === 1) cased.add(cps[0]!.codePointAt(0)!);
    }
  }
  const members = [...cased].sort((a, b) => a - b);
  const strings = members.map((cp) => String.fromCodePoint(cp));
  const fold: Record<string, number[]> = {};
  for (const c of members) {
    const re = new RegExp(`^\\u{${c.toString(16)}}$`, 'iu');
    const others = members.filter((d, i) => d !== c && re.test(strings[i]!));
    if (others.length > 0) fold[c.toString(16)] = others;
  }
  return {
    note: 'Generated by scripts/parity/go-probes-answers.ts; do not edit.',
    node: process.version,
    unicode: process.versions.unicode,
    lnFold: ranges((cp) => lnFold.test(String.fromCodePoint(cp))),
    candidates: members.length,
    fold,
  };
}

