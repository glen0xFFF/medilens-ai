/**
 * Extra reference outputs for the Go port of the spoken summary and the
 * deterministic answers (task G4), recorded from the Node build. The parity
 * corpora replay the TS test suite; these probe the places where JS and Go
 * differ by construction in summary.ts and answers.ts.
 *
 *   npx tsx scripts/parity/go-probes-answers.ts
 *
 * Deterministic (seeded mulberry32, sorted output); re-running gives the
 * same files. After the Node server is removed (task G12) re-recording needs
 * `apps/server` restored from the tag first (not a whole-tree checkout:
 * the tag predates scripts/parity): see scripts/parity/README.md#re-recording. Writes:
 *
 * 1. internal/domain/testdata/answers_casefold.json: the `iu` RegExp
 *    semantics `locate` (answers.ts) relies on, per code point:
 *    - `lnFold`: the code points `/^[\p{L}\p{N}]$/iu` matches (the class of
 *      the phrase's word-boundary lookarounds, under case-insensitive
 *      matching);
 *    - `fold`: for every code point with a case mapping (and every
 *      single-code-point target of one), the other code points a
 *      `/^\u{c}$/iu` literal matches.
 * 2. internal/domain/testdata/answers_regexps.json: the source and flags of
 *    every RegExp run while the probes below run (literal or constructed),
 *    so the Go test can check that each pattern the Go port compiles from a
 *    TS source is exactly a source V8 ran.
 * 3. internal/domain/testdata/answers_unicode.jsonl: corpus-format lines
 *    (fn, args, result) for findPhraseInFields, explainQuote,
 *    composeExplainAnswer, explanationAllowed, explanationFits,
 *    quoteExplainable, answerFromLabel and buildSummary on non-ASCII inputs:
 *    case-fold variants (Kelvin sign, long s, final sigma, ypogegrammeni,
 *    dotted and dotless i, sharp s, Deseret), NFKC compatibility forms,
 *    format characters, typographic quotes and dashes, astral characters
 *    in long printed values (UTF-16 lengths in the 400-unit chunker), and
 *    hard-cut words.
 *
 * Every recorded string is well-formed UTF-16 (no lone surrogate), because
 * a Go string decoded from JSON cannot carry one: a probe whose result has
 * one is not recorded.
 */
