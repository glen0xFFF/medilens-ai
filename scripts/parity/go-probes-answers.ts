/** A long printed value: astral characters, sentences and one unbroken run. */
function longValue(rnd: () => number): string {
  const words = ['take', 'Tablet', '\u{1d400}\u{1d401}', '\u{1f48a}', 'café', 'e.g.', '2.5', 'mL'];
  const parts: string[] = [];
  const n = 60 + Math.floor(rnd() * 120);
  for (let i = 0; i < n; i++) {
    let w = pick(rnd, words);
    if (rnd() < 0.08) w += '.';
    if (rnd() < 0.05) w = w.charAt(0).toUpperCase() + w.slice(1);
    parts.push(w);
  }
  if (rnd() < 0.5) {
    const run = Array.from({ length: 150 + Math.floor(rnd() * 400) }, () =>
      pick(rnd, ['a', '\u{1d400}', 'é', '\u{1f48a}']),
    ).join('');
    parts.splice(Math.floor(rnd() * parts.length), 0, run);
  }
  return parts.join(pick(rnd, [' ', '  ', '  ', '\t']));
}

/* ------------------------------------------ intercepting the RegExps */

const OriginalRegExp = RegExp;
const originalExec = RegExp.prototype.exec;
/** The string a RegExp was constructed from (its `.source` escapes `/`). */
const constructedFrom = new WeakMap<RegExp, string>();
const seenRegexps = new Map<string, { source: string; flags: string }>();
let capturing = false;

/** test(), replace(), split() and match() all reach exec(), the one hook needed. */
function installInterceptors(): void {
  globalThis.RegExp = new Proxy(OriginalRegExp, {
    construct(target, args: [string | RegExp, string?], newTarget) {
      const re = Reflect.construct(target, args, newTarget) as RegExp;
      if (typeof args[0] === 'string') constructedFrom.set(re, args[0]);
      return re;
    },
  });
  RegExp.prototype.exec = function (this: RegExp, s: string) {
    const source = constructedFrom.get(this) ?? this.source;
    if (capturing) seenRegexps.set(`${source}\u0000${this.flags}`, { source, flags: this.flags });
    return originalExec.call(this, s);
  };
}

function removeInterceptors(): void {
  globalThis.RegExp = OriginalRegExp;
  RegExp.prototype.exec = originalExec;
}

async function functionProbes(): Promise<string[]> {
  const answers = await import('../../apps/server/src/domain/answers');
  const summary = await import('../../apps/server/src/domain/summary');
  const rnd = prng(20261029);
  const lines = new Map<string, string>();
  // RegExps are noted only while a domain function runs, not the probe's own
  const record = (fn: string, args: unknown[], call: () => unknown) => {
    capturing = true;
    let result: unknown;
    try {
      result = call();
    } finally {
      capturing = false;
    }
    const line = encodeJson({ fn, args, result });
    if (!wellFormed(line)) return;
    lines.set(`${fn}\u0000${JSON.stringify(args)}`, line);
  };

  // phrases in printed values, as clear and as partly legible fields
  // (a label of the printed value and its two neighbours, so a phrase can
  // also be found in a later field)
  for (const legibility of ['clear', 'partial'] as const) {
    PRINTED.forEach(([key, value], i) => {
      const before = PRINTED[(i + PRINTED.length - 1) % PRINTED.length]!;
      const after = PRINTED[(i + 1) % PRINTED.length]!;
      const lbl = label([
        field(before[0], before[1], 'clear'),
        field(key, value, legibility),
        field(after[0], after[1], 'clear'),
      ]);
      let n = 0;
      for (const p of phrasesOf(rnd, value)) {
        for (const phrase of variants(rnd, p)) {
          record('findPhraseInFields', [phrase, lbl], () =>
            answers.findPhraseInFields(phrase, lbl),
          );
          record('explainQuote', [phrase, lbl], () => answers.explainQuote(phrase, lbl));
          const input = {
            label: lbl,
            match: DEMO_MATCH,
            question: 'What does this mean?',
            intent: 'explain_text' as const,
          };
          const explanation = n++ % 2 === 0 ? null : pick(rnd, EXPLANATIONS);
          record('composeExplainAnswer', [input, phrase, explanation], () =>
            answers.composeExplainAnswer(input, phrase, explanation),
          );
        }
      }
    });
  }

  // the closed-vocabulary gate on Unicode variants
  for (const e of EXPLANATIONS) {
    for (const [, m] of TEXT_MUTATIONS) {
      const x = m(e);
      record('explanationAllowed', [x], () => answers.explanationAllowed(x));
      for (const p of PRINTED_TEXTS) {
        record('explanationFits', [x, p], () => answers.explanationFits(x, p));
      }
    }
  }
  for (const p of PRINTED_TEXTS) {
    for (const [, m] of TEXT_MUTATIONS) {
      const x = m(p);
      record('quoteExplainable', [x], () => answers.quoteExplainable(x));
      for (const e of EXPLANATIONS)
        record('explanationFits', [e, x], () => answers.explanationFits(e, x));
    }
  }

  // read-backs of non-ASCII and long values
  for (let n = 0; n < 24; n++) {
    const legible = (): Legibility => pick(rnd, ['clear', 'clear', 'partial', 'unreadable']);
    const fields = PRINTED.filter(() => rnd() < 0.6).map(([k, v]) => field(k, v, legible()));
    fields.push(field('directions', longValue(rnd), legible()));
    if (rnd() < 0.5) fields.push(field('warnings', longValue(rnd), legible()));
    if (rnd() < 0.5) fields.push(field('expiryDate', longValue(rnd), legible()));
    const lbl = label(fields);
    for (const [intent, question] of [pick(rnd, ASK), pick(rnd, ASK), pick(rnd, ASK)]) {
      const input = { label: lbl, match: DEMO_MATCH, question, intent: intent as 'read_label' };
      record('answerFromLabel', [input], () => answers.answerFromLabel(input));
    }
    const input = {
      label: lbl,
      quality: { ok: true, sharpness: 120, luminance: 128, glareFraction: 0, reasons: [] },
      match: DEMO_MATCH,
      isDemo: rnd() < 0.5,
      pipelineState: 'explanation_ready' as const,
    };
    record('buildSummary', [input], () => summary.buildSummary(input));
  }

  return [...lines.entries()].sort(([a], [b]) => byCodeUnits(a, b)).map(([, l]) => l);
}

function writeLines(rel: string, lines: string[]): void {
  mkdirSync(path.dirname(out(rel)), { recursive: true });
  writeFileSync(out(rel), `${lines.join('\n')}\n`);
  console.log(`${rel}: ${lines.length} lines`);
}

async function main(): Promise<void> {
  installInterceptors();
  const lines = await functionProbes();
  removeInterceptors();
  const regexps = [...seenRegexps.values()].sort(
    (a, b) => byCodeUnits(a.source, b.source) || byCodeUnits(a.flags, b.flags),
  );
  writeFileSync(
    out('internal/domain/testdata/answers_regexps.json'),
    `${JSON.stringify({ note: 'Generated by scripts/parity/go-probes-answers.ts; do not edit.', regexps })}
`,
  );
  console.log(`internal/domain/testdata/answers_regexps.json: ${regexps.length} patterns`);
  const tables = caseFoldTables();
  writeFileSync(
    out('internal/domain/testdata/answers_casefold.json'),
    `${JSON.stringify(tables)}\n`,
  );
  console.log('internal/domain/testdata/answers_casefold.json: written');
  writeLines('internal/domain/testdata/answers_unicode.jsonl', lines);
}

await main();
