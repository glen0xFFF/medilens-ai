/** Code points whose case variants a `/iu` literal folds together. */
const FOLD_VARIANTS: Record<string, string[]> = {
  k: ['K', 'K'],
  s: ['S', 'ſ'],
  σ: ['Σ', 'ς'],
  ι: ['Ι', 'ͅ', 'ι'],
  ω: ['Ω', 'Ω'],
  å: ['Å', 'Å'],
  ß: ['ẞ'],
  i: ['I', 'İ', 'ı'],
  ǆ: ['Ǆ', 'ǅ'],
  '\u{10428}': ['\u{10400}'],
  e: ['E', 'é'],
  "'": ['’', '‘', '`'],
  '-': ['–', '—'],
  ' ': [' ', '\t', '  ', ' '],
};

function variants(rnd: () => number, phrase: string): string[] {
  const cps = [...phrase];
  const outs = new Set<string>([phrase, phrase.toUpperCase(), phrase.toLowerCase()]);
  for (let n = 0; n < 4; n++) {
    outs.add(
      cps
        .map((c) => {
          const key = c.toLowerCase();
          const vs = FOLD_VARIANTS[key] ?? FOLD_VARIANTS[c];
          if (vs === undefined || rnd() < 0.4) return c;
          return pick(rnd, [key, ...vs]);
        })
        .join(''),
    );
  }
  return [...outs];
}

function phrasesOf(rnd: () => number, value: string): string[] {
  const words = value.split(/\s+/).filter(Boolean);
  const out = new Set<string>();
  for (let n = 0; n < 6; n++) {
    const i = Math.floor(rnd() * words.length);
    const len = 1 + Math.floor(rnd() * 3);
    out.add(words.slice(i, i + len).join(' '));
  }
  // part of a word, never a hit
  const w = pick(rnd, words);
  if ([...w].length > 3) out.add([...w].slice(1, -1).join(''));
  out.add(value);
  return [...out];
}

